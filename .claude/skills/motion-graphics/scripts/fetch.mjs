#!/usr/bin/env node
// fetch.mjs: find and download royalty-free music, SFX, packs, fonts and icons into a film project,
// with license tracking. Files are cached in ~/.cache/motion-graphics and copied into the project;
// every download is recorded in credits.json and CREDITS.md in the project root (run from there).
//
//   node fetch.mjs music [--mood calm] [--genre lofi] [--energy 2-3] [--license cc0,cc-by,pd,mixkit] [--broadcast] [--content-id]
//   node fetch.mjs sfx [--category whoosh] [--q impact]
//   node fetch.mjs packs
//   node fetch.mjs get <id> [<id> ...]           # music or sfx id from the lists above, or ov:<openverse-uuid>
//   node fetch.mjs pack <pack-id>                # zip -> audio/packs/<pack-id>/
//   node fetch.mjs search "<query>" [--license cc0,by]   # live Openverse audio search (CC0/CC BY only)
//   node fetch.mjs font <fontsource-id> [--weights 400,700] [--italic]
//   node fetch.mjs fonts [--role display]        # list the curated families
//   node fetch.mjs icon <set>:<name> [...] [--color "#141413"]   # any Iconify set, e.g. lucide:rocket, ph:house-duotone
//   node fetch.mjs credits                       # print CREDITS.md
//
// License policy (enforced): commercial use allowed; no NC, ND or SA. Content ID registered tracks are hidden
// unless --content-id. Mixkit is hidden with --broadcast (its license bans TV/radio broadcast).

import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, readdirSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import path from 'node:path';
import os from 'node:os';

const LIB = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'library');
const CACHE = path.join(os.homedir(), '.cache', 'motion-graphics');
const UA = 'motion-graphics-skill/1.0 (+https://github.com/magnusrodseth/dotfiles)';
const argv = process.argv.slice(2);
const cmd = argv[0];
const flag = (k) => argv.includes('--' + k);
const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d; };
const VALUED = new Set(['mood', 'genre', 'energy', 'license', 'category', 'q', 'weights', 'color', 'role']); // flags that take a value
const positional = argv.slice(1).filter((a, i, all) => !a.startsWith('--') && !(all[i - 1] && all[i - 1].startsWith('--') && VALUED.has(all[i - 1].slice(2))));
const load = (n) => JSON.parse(readFileSync(path.join(LIB, `${n}.json`), 'utf8'));
const die = (m) => { console.error(m); process.exit(1); };

// ---- license policy: allowlist ----
const norm = (lic) => String(lic).trim().toUpperCase().replace(/[\s_]+/g, '-');
const BAD = /(^|-)(NC|ND|SA|SAMPLING\+?)(-|$)|GPL|PERSONAL/i;
const OK = /^(CC0(-1\.0)?|PD|PUBLIC-DOMAIN|CC-BY-[1-4]\.0|MIXKIT|PIXABAY|OFL(-1\.1)?|ISC|MIT|APACHE-2\.0|0BSD|BSD-[23]-CLAUSE|CC-BY-4\.0)$/;
const famOf = (lic) => { const l = String(lic).toUpperCase(); if (l.startsWith('CC0') || l === 'PD' || l.includes('PUBLIC')) return 'cc0'; if (l.startsWith('CC-BY')) return 'cc-by'; return l.toLowerCase(); };
function allowed(item, { broadcast = false } = {}) {
  const l = norm(item.license);
  if (BAD.test(l) || !OK.test(l)) return false;
  if (broadcast && /mixkit/i.test(item.license)) return false;
  return true;
}

// ---- credits ----
const clean = (v, n = 160) => (v == null ? v : String(v).replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\|/g, '/').replace(/\s+/g, ' ').trim().slice(0, n));
function credit(entry) {
  entry = Object.fromEntries(Object.entries(entry).map(([k, v]) => [k, typeof v === 'string' ? clean(v, k === 'attribution' ? 300 : 160) : v]));
  const f = 'credits.json';
  const list = existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : [];
  if (!list.some((e) => e.id === entry.id && e.file === entry.file)) list.push({ ...entry, added: new Date().toISOString().slice(0, 10) });
  writeFileSync(f, JSON.stringify(list, null, 1));
  const lines = ['# Credits', '', 'Generated by motion-graphics fetch.mjs. Keep this file with the film; put the "Credit line" entries in the video description or end card.', '',
    '| Asset | Kind | Creator | License | Credit line | Source |', '|---|---|---|---|---|---|'];
  for (const e of list) lines.push(`| ${e.title} | ${e.kind} | ${e.creator || ''} | ${e.license} | ${e.attribution || 'not required'} | ${e.page || e.url} |`);
  const req = list.filter((e) => e.attribution);
  if (req.length) lines.push('', '## Credit lines to publish', '', ...req.map((e) => `- ${e.attribution}`));
  writeFileSync('CREDITS.md', lines.join('\n') + '\n');
}

// ---- download with cache ----
function safeUrl(url) {
  let u; try { u = new URL(url); } catch { die(`bad url: ${url}`); }
  if (u.protocol !== 'https:') die(`refusing non-https url: ${url}`);
  if (/^(localhost|127\.|10\.|192\.168\.|169\.254\.|172\.(1[6-9]|2\d|3[01])\.|0\.|\[?::1\]?$|\[?f[cd])/i.test(u.hostname)) die(`refusing private host: ${url}`);
  return u.href;
}
async function download(url, ext, headers = {}) {
  url = safeUrl(url);
  mkdirSync(CACHE, { recursive: true });
  const file = path.join(CACHE, createHash('sha1').update(url).digest('hex').slice(0, 16) + ext);
  if (existsSync(file) && statSync(file).size > 0) return file;
  const r = await fetch(url, { headers: { 'user-agent': UA, ...headers }, redirect: 'follow' });
  if (!r.ok) die(`download failed ${r.status}: ${url}`);
  writeFileSync(file, Buffer.from(await r.arrayBuffer()));
  return file;
}
const extOf = (url, fallback) => { const m = new URL(url).pathname.match(/\.(mp3|ogg|wav|flac|m4a|ttf|otf|woff2?|svg|png|zip)$/i); return m ? '.' + m[1].toLowerCase() : fallback; };

function table(rows, cols) {
  const w = cols.map((c) => Math.min(48, Math.max(c.length, ...rows.map((r) => String(r[c] ?? '').length))));
  console.log(cols.map((c, i) => c.padEnd(w[i])).join('  '));
  for (const r of rows) console.log(cols.map((c, i) => String(r[c] ?? '').slice(0, 48).padEnd(w[i])).join('  '));
  console.log(`(${rows.length})`);
}

// ---- commands ----
async function main() {
  if (cmd === 'music') {
    const m = load('music');
    let rows = [...m.tracks, ...(flag('content-id') ? m.tracks_content_id_registered.map((t) => ({ ...t, content_id: true })) : [])];
    const mood = opt('mood'), genre = opt('genre'), energy = opt('energy'), lic = opt('license');
    rows = rows.filter((t) => allowed(t, { broadcast: flag('broadcast') }));
    if (mood) rows = rows.filter((t) => t.mood.some((x) => x.includes(mood)));
    if (genre) rows = rows.filter((t) => (t.genre || '').toLowerCase().includes(genre.toLowerCase()));
    if (energy) { const [a, b = a] = energy.split('-').map(Number); rows = rows.filter((t) => t.energy >= a && t.energy <= b); }
    if (lic) { const set = lic.split(','); rows = rows.filter((t) => set.includes(famOf(t.license))); }
    table(rows.map((t) => ({ id: t.id, title: t.title, artist: t.artist, license: t.license + (t.content_id ? ' [ContentID]' : ''), energy: t.energy, bpm: t.bpm ?? '', dur: t.duration_s ?? '', mood: t.mood.join(','), genre: t.genre })),
      ['id', 'title', 'artist', 'license', 'energy', 'bpm', 'dur', 'mood', 'genre']);
  } else if (cmd === 'sfx') {
    const s = load('sfx');
    let rows = s.sounds.filter((x) => allowed(x));
    const cat = opt('category'), q = opt('q');
    if (cat) rows = rows.filter((x) => x.category.includes(cat));
    if (q) rows = rows.filter((x) => (x.title + ' ' + x.tags.join(' ')).toLowerCase().includes(q.toLowerCase()));
    table(rows.map((x) => ({ id: x.id, category: x.category, title: x.title, license: x.license, dur: x.duration_s })), ['id', 'category', 'title', 'license', 'dur']);
    if (!cat && !q) console.log('categories: ' + [...new Set(s.sounds.map((x) => x.category))].join(', '));
  } else if (cmd === 'packs') {
    const s = load('sfx');
    table(s.packs.map((p) => ({ id: p.id, files: p.file_count ?? '', license: p.license, format: p.format ?? '', contents: p.contents_summary })), ['id', 'files', 'license', 'format', 'contents']);
  } else if (cmd === 'get') {
    if (!positional.length) die('get <id> [...]');
    const m = load('music'), s = load('sfx');
    const all = [...m.tracks.map((t) => ({ ...t, kind: 'music' })), ...m.tracks_content_id_registered.map((t) => ({ ...t, kind: 'music', content_id: true })), ...s.sounds.map((x) => ({ ...x, kind: 'sfx', artist: x.creator }))];
    const cid = flag('content-id');
    for (const id of positional) {
      let item = all.find((x) => x.id === id);
      if (id.startsWith('ov:')) item = await openverseItem(id.slice(3));
      if (!item) die(`unknown id: ${id} (list with: music | sfx | search)`);
      if (!allowed(item)) die(`license not allowed for ${id}: ${item.license}`);
      if (item.content_id && !cid) die(`${id} is registered with YouTube Content ID; pass --content-id to download it anyway.`);
      if (item.content_id) console.warn(`WARN ${id} is registered with YouTube Content ID: put "${item.attribution}" in the video description or avoid YouTube.`);
      if (/mixkit/i.test(item.license)) console.warn(`NOTE ${id}: Mixkit license bans TV/radio broadcast; web and social are fine.`);
      const ext = extOf(item.url, '.mp3');
      const cached = await download(item.url, ext, /wikimedia/.test(item.url) ? { 'user-agent': UA } : {});
      const dir = item.kind === 'music' ? 'audio/music' : 'audio/sfx';
      mkdirSync(dir, { recursive: true });
      const dest = path.join(dir, `${id.replace(/^ov:/, 'ov-').replace(/[^a-zA-Z0-9._-]/g, '_')}${ext}`);
      copyFileSync(cached, dest);
      credit({ id, file: dest, kind: item.kind, title: item.title, creator: item.artist || item.creator, license: item.license, license_url: item.license_url, attribution: item.attribution, page: item.page, url: item.url, content_id: !!item.content_id });
      const dur = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', dest]).stdout.toString().trim();
      console.log(`${path.resolve(dest)}  ${item.license}  ${Number(dur).toFixed(1)}s${item.bpm ? `  ${item.bpm} BPM` : ''}`);
    }
    if (positional.some((id) => all.find((x) => x.id === id)?.kind === 'music')) console.log('Measure beats before cutting: uv run --with librosa --with numpy python $S/beats.py audio/music/<file> > audio/beats.json');
  } else if (cmd === 'pack') {
    const id = positional[0]; const s = load('sfx'); const p = s.packs.find((x) => x.id === id); // ids come from the curated catalog only
    if (!p) die(`unknown pack ${id} (list with: packs)`);
    if (!allowed(p)) die(`license not allowed: ${p.license}`);
    let url = p.url;
    if (/kenney\.nl\/download-link/.test(url)) url = await kenneySigned(p);
    const zip = await download(url, '.zip');
    const dir = path.join('audio/packs', id); mkdirSync(dir, { recursive: true });
    const r = spawnSync('unzip', ['-o', '-q', zip, '-d', dir]); if (r.status) die(String(r.stderr));
    const count = spawnSync('bash', ['-c', `find "${dir}" -type f \\( -iname '*.ogg' -o -iname '*.wav' -o -iname '*.mp3' -o -iname '*.flac' \\) | wc -l`]).stdout.toString().trim();
    credit({ id, file: dir, kind: 'sfx-pack', title: p.name, creator: p.source, license: p.license, license_url: p.license_url, attribution: p.attribution, page: p.page, url: p.url });
    console.log(`${path.resolve(dir)}  ${count} audio files  ${p.license}`);
  } else if (cmd === 'search') {
    const q = positional.join(' '); if (!q) die('search "<query>"');
    const lic = (opt('license', 'cc0,by')).split(',').filter((l) => ['cc0', 'by', 'pdm'].includes(l)).join(',');
    const u = `https://api.openverse.org/v1/audio/?q=${encodeURIComponent(q)}&license=${lic}&page_size=20`;
    const r = await fetch(u, { headers: { 'user-agent': UA } }); if (!r.ok) die(`openverse ${r.status}`);
    const j = await r.json();
    table(j.results.map((x) => ({ id: 'ov:' + x.id, title: x.title, creator: x.creator, license: `${x.license} ${x.license_version}`, dur: x.duration ? (x.duration / 1000).toFixed(1) : '', source: x.source })), ['id', 'title', 'creator', 'license', 'dur', 'source']);
    console.log('Download with: node fetch.mjs get ov:<uuid>   (Openverse limits anonymous use to ~20 requests/min)');
  } else if (cmd === 'fonts') {
    const v = load('visual'); let fam = v.fonts.families; const role = opt('role');
    if (role) fam = fam.filter((f) => f.role.includes(role));
    table(fam.map((f) => ({ id: f.fontsource_id, family: f.family, role: f.role, weights: f.weights.join(','), axes: Object.keys(f.variable_axes || {}).join(','), notes: f.notes })), ['id', 'family', 'role', 'weights', 'axes', 'notes']);
  } else if (cmd === 'font') {
    const id = positional[0]; if (!id || !/^[a-z0-9-]+$/.test(id)) die('font <fontsource-id> [--weights 400,700]');
    const v = load('visual'); const f = v.fonts.families.find((x) => x.fontsource_id === id);
    let license = f?.license;
    if (!f) { const r = await fetch(`https://api.fontsource.org/v1/fonts/${encodeURIComponent(id)}`, { headers: { 'user-agent': UA } }); if (!r.ok) die(`unknown font ${id} (${r.status})`);
      const meta = await r.json(); license = meta.license?.type || meta.license || 'unknown'; console.warn(`note: ${id} is not in the curated catalog; Fontsource reports license ${JSON.stringify(license)}`); }
    if (!/OFL|Apache|MIT|UFL/i.test(String(license))) die(`font ${id} license ${license} not allowed`);
    const weights = opt('weights', '400,700').split(',').filter((w) => /^\d{3}$/.test(w));
    let copied = 0;
    const style = flag('italic') ? 'italic' : 'normal';
    mkdirSync('assets/fonts', { recursive: true });
    for (const w of weights) {
      const url = `https://cdn.jsdelivr.net/fontsource/fonts/${id}@latest/latin-${w}-${style}.ttf`;
      const head = await fetch(url, { method: 'HEAD', headers: { 'user-agent': UA } });
      if (!head.ok) { console.warn(`skip ${id} ${w} ${style}: not published (${head.status}); weights: ${f?.weights?.join(',') || 'see fontsource.org'}`); continue; }
      const cached = await download(url, '.ttf');
      const dest = `assets/fonts/${id}-${w}${style === 'italic' ? 'i' : ''}.ttf`;
      copyFileSync(cached, dest); copied++;
      console.log(`${path.resolve(dest)}   FontFace('${f?.family || id}', 'url(${dest})', { weight: '${w}', style: '${style}' })`);
    }
    if (copied) credit({ id: 'font:' + id, file: 'assets/fonts', kind: 'font', title: f?.family || id, creator: 'Google Fonts / Fontsource', license: String(license), attribution: null, page: `https://fontsource.org/fonts/${id}`, url: 'https://cdn.jsdelivr.net/fontsource/' });
    else die(`no weights of ${id} were downloaded`);
  } else if (cmd === 'icon') {
    if (!positional.length) die('icon <set>:<name> [...]');
    const color = opt('color'); mkdirSync('assets/icons', { recursive: true });
    const sets = [...new Set(positional.map((x) => x.split(':')[0]))];
    const meta = await (await fetch(`https://api.iconify.design/collections?prefixes=${sets.join(',')}`, { headers: { 'user-agent': UA } })).json();
    for (const ic of positional) {
      const [set, name] = ic.split(':'); if (!/^[a-z0-9-]+$/.test(set || '') || !/^[a-z0-9-]+$/.test(name || '')) die(`bad icon name ${ic}`); const m = meta[set];
      if (!m) die(`unknown icon set ${set}`);
      const spdx = m.license?.spdx || m.license?.title || 'unknown';
      if (BAD.test(norm(spdx)) || !OK.test(norm(spdx))) die(`icon set ${set} license ${spdx} not allowed`);
      const url = `https://api.iconify.design/${set}/${name}.svg${color ? `?color=${encodeURIComponent(color)}` : ''}`;
      const r = await fetch(url, { headers: { 'user-agent': UA } }); const svg = await r.text();
      if (!r.ok || !svg.startsWith('<svg')) die(`icon not found: ${ic}`);
      const dest = `assets/icons/${set}-${name}.svg`; writeFileSync(dest, svg);
      credit({ id: 'icons:' + set, file: 'assets/icons', kind: 'icon', title: m.name, creator: m.author?.name, license: spdx, attribution: /CC-BY/i.test(spdx) ? `${m.name} by ${m.author?.name} (${spdx})` : null, page: m.author?.url || `https://icon-sets.iconify.design/${set}/`, url });
      console.log(`${path.resolve(dest)}  ${m.name} (${spdx})`);
    }
  } else if (cmd === 'credits') {
    console.log(existsSync('CREDITS.md') ? readFileSync('CREDITS.md', 'utf8') : 'no credits yet');
  } else {
    console.log(readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).map((l) => l.slice(3)).join('\n'));
  }
}

async function openverseItem(uuid) {
  const r = await fetch(`https://api.openverse.org/v1/audio/${uuid}/`, { headers: { 'user-agent': UA } });
  if (!r.ok) die(`openverse ${r.status} for ${uuid}`);
  const x = await r.json();
  const map = { cc0: 'CC0-1.0', pdm: 'PD', by: `CC-BY-${x.license_version}` };
  const license = map[x.license]; if (!license) die(`Openverse item ${uuid} has license ${x.license} ${x.license_version}; only cc0, pdm and by are allowed`);
  return { id: 'ov:' + uuid, kind: x.category === 'music' ? 'music' : 'sfx', title: x.title, artist: x.creator, license, license_url: x.license_url,
    attribution: license === 'CC0-1.0' || license === 'PD' ? null : x.attribution, page: x.foreign_landing_url, url: x.url };
}

// Kenney: the download endpoint needs the session cookie from the asset page and returns a signed URL.
async function kenneySigned(p) {
  const page = await fetch(p.page, { headers: { 'user-agent': UA } });
  const cookies = (page.headers.getSetCookie?.() || []).map((c) => c.split(';')[0]).join('; ');
  const r = await fetch(p.url, { headers: { 'user-agent': UA, cookie: cookies, referer: p.page, 'x-requested-with': 'XMLHttpRequest' } });
  const txt = await r.text();
  try { const j = JSON.parse(txt); if (j.url && /^https:\/\/([a-z0-9-]+\.)*kenney\.nl\//.test(j.url)) return j.url; } catch {}
  die(`kenney signed link failed (${r.status}): ${txt.slice(0, 120)}. Download by hand from ${p.page}`);
}

await main();
